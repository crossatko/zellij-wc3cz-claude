#!/bin/sh
# Optional: make the WC3 icon font (colour character icons in the tab bar) available to every terminal that
# uses fontconfig, without editing any terminal config. Linux only. Run it yourself, or via `setup.sh --font`.
#   fontconfig/install.sh               install / update (idempotent)
#   fontconfig/install.sh --uninstall   remove the files again
#   fontconfig/install.sh --check       show what fontconfig picks now, change nothing
#   fontconfig/install.sh --print-conf  print the fontconfig rules generated from the font, change nothing
# Writes exactly three files, all owned by this package (nothing else is touched):
#   ${XDG_DATA_HOME:-~/.local/share}/fonts/wc3-icons.ttf             (copy of assets/wc3-icons/wc3-icons.ttf)
#   ${XDG_DATA_HOME:-~/.local/share}/fonts/wc3-icons-wide.ttf        (copy of assets/wc3-icons/wc3-icons-wide.ttf)
#   ${XDG_CONFIG_HOME:-~/.config}/fontconfig/conf.d/60-wc3-icons.conf (rules, generated from the font)
# --uninstall also removes fonts/wc3-icons-custom.ttf if it is a "WC3 Icons Custom" build (assets/wc3-icons/README.md).
# then runs fc-cache on the font dir (creating the conf.d dir if missing) and removes the plugin's cached
# font flag /tmp/zellij-<uid>/zellij-claude/font so the bar re-checks at the next hook event. The rules make fontconfig prefer "WC3 Icons" for the CHARACTER icon
# codepoints of the font (U+1FA70.., one per character); other emoji and all text are unaffected. The seven
# race fallback codepoints U+1F7E0..U+1F7E6 (orange..brown circle emoji) are NOT overridden.
# Side effect (every app using fontconfig, e.g. browsers): those few emoji (ballet shoes, ringed planet, ...)
# show WC3 portraits. --uninstall reverts it. An existing wc3-icons*.ttf of another font is never overwritten.
# The rules also tag the WC3 Icons families as emoji fonts (lang und-zsye, applied when fc-cache scans them):
# foot (fcft) only takes an emoji-presentation codepoint from a fallback font with that tag.
set -u
here=$(cd "$(dirname "$0")" && pwd -P)
font_src="$here/../assets/wc3-icons/wc3-icons.ttf"
family="WC3 Icons"
marker="generated by zellij-wc3cz fontconfig/install.sh"
font_dir="${XDG_DATA_HOME:-$HOME/.local/share}/fonts"
font_dst="$font_dir/wc3-icons.ttf"
wide_src="$here/../assets/wc3-icons/wc3-icons-wide.ttf"
wide_family="WC3 Icons Wide"
wide_dst="$font_dir/wc3-icons-wide.ttf"
custom_family="WC3 Icons Custom"
custom_dst="$font_dir/wc3-icons-custom.ttf"
conf_dir="${XDG_CONFIG_HOME:-$HOME/.config}/fontconfig/conf.d"
conf_dst="$conf_dir/60-wc3-icons.conf"

mode=install
case "${1:-}" in
  "") ;;
  --uninstall) mode=uninstall ;;
  --check) mode=check ;;
  --print-conf) mode=print ;;
  -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
  *) echo "unknown option $1 (see --help)" >&2; exit 2 ;;
esac

say() { printf '  wc3-icons: %s\n' "$*"; }

case "$(uname -s)" in
  Linux|*BSD|DragonFly) ;;
  Darwin) say "macOS is not supported: CoreText cannot draw this CBDT colour bitmap font."
          say "Nothing installed. The tab bar shows initials badges instead."; exit 0 ;;
  *) say "$(uname -s) is not supported (needs fontconfig). Nothing installed; the tab bar uses initials badges."
     exit 0 ;;
esac
for t in fc-query fc-match; do
  command -v "$t" >/dev/null 2>&1 || { say "$t not found (fontconfig missing). Nothing installed."; exit 1; }
done

# conf_text: the rules for the character icon codepoints the font really has (read with fc-query, so they
# follow font rebuilds). Skipped: the race fallback codepoints U+1F7E0..U+1F7E6 (common status-dot emoji).
conf_text() {
  cs=$(fc-query -f '%{charset}' "$font_src" 2>/dev/null)
  [ -n "$cs" ] || { echo "cannot read the charset of $font_src" >&2; return 1; }
  cat <<EOF
<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- $marker; do not edit (rerun the script). -->
<!-- WC3 Icons (zellij claude-tabs character icons) wins for its character icon codepoints only (font charset: $cs, minus the race fallbacks 1f7e0-1f7e6, which stay with the system emoji font). -->
<fontconfig>
  <!-- Lookups with a charset (kitty asks per character, also for family "emoji" + color): WC3 Icons first. -->
EOF
  for r in $cs; do
    lo=${r%-*}; hi=${r#*-}
    i=$(printf '%d' "0x$lo"); end=$(printf '%d' "0x$hi")
    while [ "$i" -le "$end" ]; do
      if [ "$i" -lt 128992 ] || [ "$i" -gt 128998 ]; then   # not U+1F7E0..U+1F7E6
        printf '  <match target="pattern"><test name="charset" compare="contains"><charset><int>0x%x</int></charset></test><edit name="family" mode="prepend_first" binding="strong"><string>%s</string></edit></match>\n' "$i" "$family"
      fi
      i=$((i + 1))
    done
  done
  echo '  <!-- foot (fcft) takes an emoji-presentation codepoint from a fallback font only if its language set has und-zsye (emoji): tag the WC3 Icons families (applied when fc-cache scans the font). -->'
  for f in "$family" "$wide_family" "$custom_family"; do
    printf '  <match target="scan"><test name="family"><string>%s</string></test><edit name="lang" mode="assign"><langset><string>und-zsye</string></langset></edit></match>\n' "$f"
  done
  echo '</fontconfig>'
}

check() {
  for f in "$family" "$wide_family" "$custom_family"; do
    printf '  fc-list %-17s %s\n' "$f:" "$(fc-list -f '%{file} (lang %{lang})\n' ":family=$f" 2>/dev/null | head -n 1)"
  done
  for q in "emoji:color=true:charset=1fa70" "monospace:charset=1fa70" "emoji:color=true:charset=1f7e0" \
           "emoji:color=true:charset=1f600" "emoji:color=true:charset=1fae0" "monospace" "emoji"; do
    printf '  fc-match %-32s -> %s\n' "'$q'" "$(fc-match -f '%{family}' "$q" 2>/dev/null)"
  done
}

terminal_notes() {
  cat <<'EOF'
  Terminals (nothing below is changed by this script; copy the lines yourself, then fully restart the terminal).
  Measured on Linux with kitty 0.49.2, ghostty 1.3.1, alacritty 0.17.0, foot 1.28.0 (README.md, Terminals):
  - kitty: fontconfig alone is not enough (it prefers Noto Color Emoji). kitty.conf (pixel exact at 14x36 cells,
    e.g. font_size 18 + modify_font cell_height 110%):
      symbol_map U+1FA70-U+1FAD6 WC3 Icons
  - ghostty: ignores fontconfig for emoji. Config (fills 2 cells x the font's natural height at any size;
    adjust-cell-height adds background bands above/below):
      font-codepoint-map = U+1FA70-U+1FAD6=WC3 Icons Wide
  - foot: name the icon font as a fallback, same size as the text font (foot.ini). WC3 Icons fits foot's
    default 6x16 cells (monospace 8); WC3 Icons Wide fits cells about half as wide as tall (Paper Mono 18):
      [main]
      font=monospace:size=8,WC3 Icons:size=8
  - alacritty: no per-font fallback setting; add a fontconfig rule (YOUR FONT = alacritty's font family), e.g.
    ~/.config/fontconfig/conf.d/61-wc3-icons-alacritty.conf:
      <match target="pattern"><test name="prgname"><string>alacritty</string></test>
        <test name="family"><string>YOUR FONT</string></test>
        <edit name="family" mode="append" binding="same"><string>WC3 Icons Wide</string></edit></match>
    alacritty does not fit the bitmap to the cell: WC3 Icons Wide fits with font.offset.y = 0; for another
    line height build a "WC3 Icons Custom" font (assets/wc3-icons/README.md) and name that family instead.
  - a terminal that cannot draw colour bitmap fonts shows another emoji or a box: set `race_font "false"` in
    the claude-tabs plugin options (initials badges) or uninstall with --uninstall.
EOF
}

case "$mode" in
  print) conf_text; exit $? ;;
  check) check; exit 0 ;;
  uninstall)
    changed=0
    if [ -f "$conf_dst" ]; then
      if grep -qF "$marker" "$conf_dst"; then rm -f "$conf_dst" && changed=1 && say "removed $conf_dst"
      else say "$conf_dst was not written by this script, left alone"; fi
    fi
    for pair in "$font_dst|$family" "$wide_dst|$wide_family" "$custom_dst|$custom_family"; do
      dst=${pair%%|*}; fam=${pair#*|}
      [ -f "$dst" ] || continue
      if [ "$(fc-query -f '%{family}' "$dst" 2>/dev/null)" = "$fam" ]; then
        rm -f "$dst" && changed=1 && say "removed $dst"
      else say "$dst is not the $fam font, left alone"; fi
    done
    if [ "$changed" = 1 ]; then command -v fc-cache >/dev/null 2>&1 && fc-cache -f "$font_dir" >/dev/null 2>&1
      say "done; restart terminals to drop the icons"
    else say "nothing to remove"; fi
    exit 0 ;;
esac

# install
[ -f "$font_src" ] || { say "$font_src not found"; exit 1; }
[ -f "$wide_src" ] || { say "$wide_src not found"; exit 1; }
command -v fc-cache >/dev/null 2>&1 || { say "fc-cache not found (fontconfig missing). Nothing installed."; exit 1; }
if [ -f "$conf_dst" ] && ! grep -qF "$marker" "$conf_dst"; then
  say "$conf_dst exists and was not written by this script; not overwriting it. Nothing installed."; exit 1
fi
mkdir -p "$font_dir" "$conf_dir" || { say "could not create $font_dir / $conf_dir"; exit 1; }
font_tmp=
tmp=$(mktemp "$conf_dir/.wc3-icons.conf.XXXXXX") || { say "could not create a temp file in $conf_dir"; exit 1; }
trap 'rm -f "$tmp" "$font_tmp"' EXIT
conf_text >"$tmp" || exit 1
changed=0
for pair in "$font_src|$font_dst|$family" "$wide_src|$wide_dst|$wide_family"; do
  src=${pair%%|*}; rest=${pair#*|}; dst=${rest%%|*}; fam=${rest#*|}
  cmp -s "$src" "$dst" && continue
  if [ -e "$dst" ] && [ "$(fc-query -f '%{family}' "$dst" 2>/dev/null)" != "$fam" ]; then
    say "$dst exists and is not the $fam font; not overwriting it. Stopped."; exit 1
  fi
  font_tmp=$(mktemp "$font_dir/.wc3-icons.ttf.XXXXXX") && cp "$src" "$font_tmp" && chmod 644 "$font_tmp" \
    && mv -f "$font_tmp" "$dst" || { say "could not write $dst"; exit 1; }
  font_tmp=
  changed=1; say "installed $dst"
done
if ! cmp -s "$tmp" "$conf_dst"; then
  chmod 644 "$tmp" && mv -f "$tmp" "$conf_dst" || { say "could not write $conf_dst"; exit 1; }
  changed=1; say "installed $conf_dst"
fi
if [ "$changed" = 1 ]; then fc-cache -f "$font_dir" >/dev/null 2>&1; say "fc-cache updated"
  # the plugin caches "font installed?" for 10 min; drop only that flag file so the next hook re-checks
  rm -f "/tmp/zellij-$(id -u)/zellij-claude/font" 2>/dev/null
else say "already installed, nothing changed"; fi
check
terminal_notes
